@Composable
fun PdxRailTheme(
    isDarkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    val density = LocalDensity.current.density
    val appDimensions = when {
        density >= 2.5f -> expandedDimensions
        density >= 1.5f -> mediumDimensions
        else            -> compactDimensions
    }
    CompositionLocalProvider(LocalAppDimensions provides appDimensions) {
        MaterialTheme(
            colorScheme = if (isDarkTheme) darkScheme else lightScheme,
            typography = PdxRailTypography,
            content = content,
        )
    }
}
